const urbanDemo = document.querySelector(".urban-ui-demo");
if (urbanDemo) {
  const screens = [...urbanDemo.querySelectorAll("[data-urban-screen]")];
  const count = urbanDemo.querySelector("[data-urban-count]");
  const caption = urbanDemo.querySelector("[data-urban-caption]");
  const dots = urbanDemo.querySelector(".urban-demo-dots");
  let activeScreen = 0;

  screens.forEach((screen, index) => {
    const dot = document.createElement("button");
    dot.type = "button";
    dot.addEventListener("click", () => {
      activeScreen = index;
      refreshUrbanScreen();
    });
    dots?.append(dot);
  });

  refreshUrbanScreen = () => {
    const isChinese = currentLanguage === "zh-CN";
    activeScreen = (activeScreen + screens.length) % screens.length;
    urbanDemo.dataset.urbanIndex = String(activeScreen);
    screens.forEach((screen, index) => { screen.hidden = index !== activeScreen; });
    if (count) count.textContent = `${String(activeScreen + 1).padStart(2, "0")} / ${String(screens.length).padStart(2, "0")}`;
    if (caption) caption.textContent = screens[activeScreen]?.dataset[isChinese ? "labelZh" : "labelEn"] || "";
    [...(dots?.children || [])].forEach((dot, index) => {
      const label = screens[index]?.dataset[isChinese ? "labelZh" : "labelEn"] || `${index + 1}`;
      dot.classList.toggle("is-active", index === activeScreen);
      dot.setAttribute("aria-label", label);
      dot.setAttribute("aria-current", index === activeScreen ? "step" : "false");
    });
  };

  const moveUrbanScreen = (delta) => {
    activeScreen += delta;
    refreshUrbanScreen();
  };
  urbanDemo.querySelector("[data-urban-prev]")?.addEventListener("click", () => moveUrbanScreen(-1));
  urbanDemo.querySelector("[data-urban-next]")?.addEventListener("click", () => moveUrbanScreen(1));
  urbanDemo.querySelector(".urban-screen-advance")?.addEventListener("click", () => moveUrbanScreen(1));
  refreshUrbanScreen();
}

const hihiFrame = document.querySelector(".hihi-source-demo iframe[data-src]");
const portfolioSection = document.querySelector("#portfolio");

function loadHihiDemo() {
  if (!hihiFrame || hihiFrame.src) return;
  hihiFrame.src = hihiFrame.dataset.src;
}

if (hihiFrame && portfolioSection) {
  if ("IntersectionObserver" in window) {
    const hihiObserver = new IntersectionObserver((entries, observer) => {
      if (!entries.some((entry) => entry.isIntersecting)) return;
      loadHihiDemo();
      observer.disconnect();
    }, { threshold: 0.05 });
    hihiObserver.observe(portfolioSection);
  } else {
    loadHihiDemo();
  }
}

document.querySelector(".hihi-demo-reset")?.addEventListener("click", () => {
  if (!hihiFrame) return;
  if (!hihiFrame.src) loadHihiDemo();
  else hihiFrame.src = hihiFrame.src;
});

const primaryNavLinks = [...document.querySelectorAll(".section-nav-top a[href^='#']")];
const observedSections = primaryNavLinks
  .map((link) => document.querySelector(link.getAttribute("href")))
  .filter(Boolean);

function setActiveNav(sectionId) {
  primaryNavLinks.forEach((link) => {
    const isCurrent = link.getAttribute("href") === `#${sectionId}`;
    link.classList.toggle("is-active", isCurrent);
    if (isCurrent) link.setAttribute("aria-current", "page");
    else link.removeAttribute("aria-current");
  });
}

if (primaryNavLinks.length && observedSections.length) {
  let navFrame = 0;
  const syncActiveNav = () => {
    navFrame = 0;
    const marker = window.scrollY + 80;
    const reachedPageEnd = Math.ceil(window.scrollY + window.innerHeight) >= document.documentElement.scrollHeight - 2;
    const currentSection = reachedPageEnd
      ? observedSections[observedSections.length - 1]
      : observedSections.reduce((current, section) => (
        section.offsetTop <= marker ? section : current
      ), observedSections[0]);
    setActiveNav(currentSection.id);
  };

  primaryNavLinks.forEach((link) => link.addEventListener("click", () => {
    setActiveNav(link.getAttribute("href").slice(1));
  }));
  window.addEventListener("scroll", () => {
    if (!navFrame) navFrame = requestAnimationFrame(syncActiveNav);
  }, { passive: true });
  syncActiveNav();
}

const experienceJumpLinks = [...document.querySelectorAll(".experience-jump-nav a[href^='#']")];
const experienceSections = experienceJumpLinks
  .map((link) => document.querySelector(link.getAttribute("href")))
  .filter(Boolean);

function setActiveExperienceJump(sectionId) {
  experienceJumpLinks.forEach((link) => {
    const isCurrent = link.getAttribute("href") === `#${sectionId}`;
    link.classList.toggle("is-active", isCurrent);
    if (isCurrent) link.setAttribute("aria-current", "location");
    else link.removeAttribute("aria-current");
  });
}

if (experienceJumpLinks.length && experienceSections.length) {
  let experienceFrame = 0;
  const syncExperienceJump = () => {
    experienceFrame = 0;
    const stickyOffset = window.matchMedia("(max-width: 720px)").matches ? 112 : 68;
    const marker = window.scrollY + stickyOffset;
    const currentSection = experienceSections.reduce((current, section) => {
      const sectionTop = section.getBoundingClientRect().top + window.scrollY;
      return sectionTop <= marker ? section : current;
    }, experienceSections[0]);
    setActiveExperienceJump(currentSection.id);
  };

  experienceJumpLinks.forEach((link) => link.addEventListener("click", () => {
    setActiveExperienceJump(link.getAttribute("href").slice(1));
  }));
  window.addEventListener("scroll", () => {
    if (!experienceFrame) experienceFrame = requestAnimationFrame(syncExperienceJump);
  }, { passive: true });
  window.addEventListener("resize", syncExperienceJump, { passive: true });
  syncExperienceJump();
}

const experienceTimeline = document.querySelector(".experience");
const timelineItems = experienceTimeline ? [
  ...experienceTimeline.querySelectorAll(".resume-group > .resume-row"),
  ...experienceTimeline.querySelectorAll(".resume-entry"),
  ...experienceTimeline.querySelectorAll(".honors-group p")
] : [];

if (experienceTimeline && timelineItems.length) {
  experienceTimeline.classList.add("timeline-enhanced");
  let timelineFrame = 0;
  const syncTimelineHighlight = () => {
    timelineFrame = 0;
    const focusLine = window.innerHeight * 0.42;
    let currentItem = timelineItems[0];
    let closestDistance = Number.POSITIVE_INFINITY;

    timelineItems.forEach((item) => {
      const rect = item.getBoundingClientRect();
      const distance = focusLine < rect.top
        ? rect.top - focusLine
        : focusLine > rect.bottom
          ? focusLine - rect.bottom
          : 0;
      if (distance < closestDistance) {
        closestDistance = distance;
        currentItem = item;
      }
    });
    timelineItems.forEach((item) => item.classList.toggle("is-current", item === currentItem));
  };

  window.addEventListener("scroll", () => {
    if (!timelineFrame) timelineFrame = requestAnimationFrame(syncTimelineHighlight);
  }, { passive: true });
  window.addEventListener("resize", syncTimelineHighlight, { passive: true });
  syncTimelineHighlight();
}
