if (projectCategory && projectCategoryTrack) {
  let isDragging = false;
  let didDrag = false;
  let suppressClick = false;
  let dragStartX = 0;
  let dragStartScroll = 0;

  const syncProjectProgress = () => {
    const maxScroll = Math.max(1, projectCategoryTrack.scrollWidth - projectCategoryTrack.clientWidth);
    const progress = Math.min(1, Math.max(0, projectCategoryTrack.scrollLeft / maxScroll));
    projectCategory.style.setProperty("--project-progress", progress.toFixed(4));
  };

  projectCategoryTrack.addEventListener("pointerdown", (event) => {
    if (event.pointerType !== "mouse" || event.button !== 0) return;
    isDragging = true;
    didDrag = false;
    dragStartX = event.clientX;
    dragStartScroll = projectCategoryTrack.scrollLeft;
    projectCategoryTrack.setPointerCapture(event.pointerId);
    projectCategory.classList.add("is-track-dragging");
    projectCategoryTrack.classList.add("is-dragging");
  });

  projectCategoryTrack.addEventListener("pointermove", (event) => {
    if (!isDragging) return;
    const distance = event.clientX - dragStartX;
    if (Math.abs(distance) > 5) didDrag = true;
    if (!didDrag) return;
    event.preventDefault();
    projectCategoryTrack.scrollLeft = dragStartScroll - distance;
    syncProjectProgress();
  });

  const finishProjectDrag = (event) => {
    if (!isDragging) return;
    isDragging = false;
    suppressClick = didDrag;
    projectCategory.classList.remove("is-track-dragging");
    projectCategoryTrack.classList.remove("is-dragging");
    if (projectCategoryTrack.hasPointerCapture(event.pointerId)) projectCategoryTrack.releasePointerCapture(event.pointerId);
    syncProjectProgress();
    window.setTimeout(() => { suppressClick = false; }, 0);
  };

  projectCategoryTrack.addEventListener("pointerup", finishProjectDrag);
  projectCategoryTrack.addEventListener("pointercancel", finishProjectDrag);
  projectCategoryTrack.addEventListener("click", (event) => {
    if (!suppressClick) return;
    event.preventDefault();
    event.stopPropagation();
  }, true);
  projectCategoryTrack.addEventListener("scroll", syncProjectProgress, { passive: true });
  window.addEventListener("resize", syncProjectProgress, { passive: true });
  requestAnimationFrame(syncProjectProgress);
}

function getProjectTitle(button) {
  return currentLanguage === "zh-CN"
    ? button?.dataset.projectTitleZh || button?.dataset.projectTitle
    : button?.dataset.projectTitle;
}

function applyLanguage(language) {
  currentLanguage = language === "zh-CN" ? "zh-CN" : "en";
  const isChinese = currentLanguage === "zh-CN";
  document.documentElement.lang = currentLanguage;

  i18nTextNodes.forEach((node) => {
    const key = node.dataset.i18n;
    node.textContent = isChinese && zhTranslations[key] ? zhTranslations[key] : originalText.get(node);
  });
  i18nHtmlNodes.forEach((node) => {
    const key = node.dataset.i18nHtml;
    node.innerHTML = isChinese && zhTranslations[key] ? zhTranslations[key] : originalHtml.get(node);
  });
  i18nAriaNodes.forEach((node) => {
    const key = node.dataset.i18nAriaLabel;
    node.setAttribute("aria-label", isChinese && zhTranslations[key] ? zhTranslations[key] : originalAria.get(node));
  });
  i18nTitleNodes.forEach((node) => {
    const key = node.dataset.i18nTitle;
    node.setAttribute("title", isChinese && zhTranslations[key] ? zhTranslations[key] : originalTitle.get(node));
  });

  document.title = isChinese ? zhTranslations["page.title"] : englishPageTitle;
  if (metaDescription) metaDescription.content = isChinese ? zhTranslations["page.description"] : englishPageDescription;
  languageToggles.forEach((toggle) => {
    toggle.dataset.language = isChinese ? "zh" : "en";
    toggle.setAttribute("aria-label", isChinese ? "Switch to English" : "切换为中文");
    toggle.setAttribute("aria-pressed", String(isChinese));
    toggle.querySelectorAll("[data-language-choice]").forEach((choice) => {
      const isCurrent = choice.dataset.languageChoice === (isChinese ? "zh" : "en");
      choice.classList.toggle("is-current", isCurrent);
      choice.setAttribute("aria-hidden", String(!isCurrent));
    });
  });
  try {
    localStorage.setItem("portfolio-language", currentLanguage);
  } catch (_error) {
    // Language persistence is optional when storage is unavailable.
  }
  refreshUrbanScreen();

  if (dialog?.open && activeProjectButton && dialogTitle) {
    dialogTitle.textContent = getProjectTitle(activeProjectButton);
  }
  document.dispatchEvent(new CustomEvent("portfolio:languagechange", {
    detail: { language: currentLanguage }
  }));
}

