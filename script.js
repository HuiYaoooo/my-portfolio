const languageToggles = [...document.querySelectorAll(".language-toggle")];
const i18nTextNodes = [...document.querySelectorAll("[data-i18n]")];
const i18nHtmlNodes = [...document.querySelectorAll("[data-i18n-html]")];
const i18nAriaNodes = [...document.querySelectorAll("[data-i18n-aria-label]")];
const i18nTitleNodes = [...document.querySelectorAll("[data-i18n-title]")];
const originalText = new Map(i18nTextNodes.map((node) => [node, node.textContent]));
const originalHtml = new Map(i18nHtmlNodes.map((node) => [node, node.innerHTML]));
const originalAria = new Map(i18nAriaNodes.map((node) => [node, node.getAttribute("aria-label")]));
const originalTitle = new Map(i18nTitleNodes.map((node) => [node, node.getAttribute("title")]));
const metaDescription = document.querySelector('meta[name="description"]');
const englishPageTitle = document.title;
const englishPageDescription = metaDescription?.content || "";
let currentLanguage = "en";
let activeProjectButton = null;

const dialog = document.querySelector("#project-dialog");
const projectFrame = dialog?.querySelector(".project-frame");
const dialogTitle = dialog?.querySelector("#dialog-title");
const openPdfLink = dialog?.querySelector(".open-pdf");
const closeDialogButton = dialog?.querySelector(".dialog-close");
const loadingLabel = dialog?.querySelector(".dialog-loading");
const projectButtons = document.querySelectorAll("[data-project-pdf]");

function getProjectTitle(button) {
  return currentLanguage === "zh-CN"
    ? button?.dataset.projectTitleZh || button?.dataset.projectTitle
    : button?.dataset.projectTitle;
}

function applyLanguage(language, persist = false) {
  currentLanguage = language === "zh-CN" ? "zh-CN" : "en";
  const isChinese = currentLanguage === "zh-CN";
  document.documentElement.lang = currentLanguage;

  i18nTextNodes.forEach((node) => {
    const key = node.dataset.i18n;
    node.textContent = isChinese && zhTranslations[key] ? zhTranslations[key] : originalText.get(node);
  });
  i18nHtmlNodes.forEach((node) => {
    const key = node.dataset.i18nHtml;
    node.innerHTML = isChinese && zhTranslations[key] ? zhTranslations[key] : originalHtml.get(node);
  });
  i18nAriaNodes.forEach((node) => {
    const key = node.dataset.i18nAriaLabel;
    node.setAttribute("aria-label", isChinese && zhTranslations[key] ? zhTranslations[key] : originalAria.get(node));
  });
  i18nTitleNodes.forEach((node) => {
    const key = node.dataset.i18nTitle;
    node.setAttribute("title", isChinese && zhTranslations[key] ? zhTranslations[key] : originalTitle.get(node));
  });

  document.title = isChinese ? zhTranslations["page.title"] : englishPageTitle;
  if (metaDescription) metaDescription.content = isChinese ? zhTranslations["page.description"] : englishPageDescription;
  languageToggles.forEach((toggle) => {
    toggle.textContent = isChinese ? "EN" : "中文";
    toggle.setAttribute("aria-label", isChinese ? "Switch to English" : "切换为中文");
    toggle.setAttribute("aria-pressed", String(isChinese));
  });

  if (dialog?.open && activeProjectButton && dialogTitle) {
    dialogTitle.textContent = getProjectTitle(activeProjectButton);
  }
  if (persist) {
    try { localStorage.setItem("portfolio-language", currentLanguage); } catch {}
  }
}

let savedLanguage = null;
try { savedLanguage = localStorage.getItem("portfolio-language"); } catch {}
const browserPrefersChinese = navigator.language?.toLowerCase().startsWith("zh");
applyLanguage(savedLanguage || (browserPrefersChinese ? "zh-CN" : "en"));
languageToggles.forEach((toggle) => toggle.addEventListener("click", () => {
  applyLanguage(currentLanguage === "zh-CN" ? "en" : "zh-CN", true);
}));

function openProject(button) {
  if (!dialog || !projectFrame || !dialogTitle || !openPdfLink) return;
  const pdfPath = button.dataset.projectPdf;
  const title = getProjectTitle(button);
  if (!pdfPath || !title) return;

  activeProjectButton = button;
  dialogTitle.textContent = title;
  openPdfLink.href = pdfPath;
  loadingLabel?.removeAttribute("hidden");
  dialog.showModal();
  document.body.classList.add("dialog-open");

  // The large PDF is loaded only after the user chooses a project.
  requestAnimationFrame(() => {
    projectFrame.src = `${pdfPath}#view=FitH`;
  });
}

function closeProject() {
  if (!dialog || !projectFrame) return;
  dialog.close();
  activeProjectButton = null;
  projectFrame.removeAttribute("src");
  loadingLabel?.removeAttribute("hidden");
  document.body.classList.remove("dialog-open");
}

projectButtons.forEach((button) => button.addEventListener("click", () => openProject(button)));
closeDialogButton?.addEventListener("click", closeProject);
projectFrame?.addEventListener("load", () => loadingLabel?.setAttribute("hidden", ""));
dialog?.addEventListener("click", (event) => { if (event.target === dialog) closeProject(); });
dialog?.addEventListener("cancel", (event) => { event.preventDefault(); closeProject(); });

const primaryNavLinks = [...document.querySelectorAll(".section-nav-top a[href^='#']")];
const observedSections = primaryNavLinks
  .map((link) => document.querySelector(link.getAttribute("href")))
  .filter(Boolean);

function setActiveNav(sectionId) {
  primaryNavLinks.forEach((link) => {
    const isCurrent = link.getAttribute("href") === `#${sectionId}`;
    link.classList.toggle("is-active", isCurrent);
    if (isCurrent) link.setAttribute("aria-current", "page");
    else link.removeAttribute("aria-current");
  });
}

if (primaryNavLinks.length && observedSections.length) {
  let navFrame = 0;
  const syncActiveNav = () => {
    navFrame = 0;
    const marker = window.scrollY + 80;
    const reachedPageEnd = Math.ceil(window.scrollY + window.innerHeight) >= document.documentElement.scrollHeight - 2;
    const currentSection = reachedPageEnd
      ? observedSections[observedSections.length - 1]
      : observedSections.reduce((current, section) => (
        section.offsetTop <= marker ? section : current
      ), observedSections[0]);
    setActiveNav(currentSection.id);
  };

  primaryNavLinks.forEach((link) => link.addEventListener("click", () => {
    setActiveNav(link.getAttribute("href").slice(1));
  }));
  window.addEventListener("scroll", () => {
    if (!navFrame) navFrame = requestAnimationFrame(syncActiveNav);
  }, { passive: true });
  syncActiveNav();
}

const experienceJumpLinks = [...document.querySelectorAll(".experience-jump-nav a[href^='#']")];
const experienceSections = experienceJumpLinks
  .map((link) => document.querySelector(link.getAttribute("href")))
  .filter(Boolean);

function setActiveExperienceJump(sectionId) {
  experienceJumpLinks.forEach((link) => {
    const isCurrent = link.getAttribute("href") === `#${sectionId}`;
    link.classList.toggle("is-active", isCurrent);
    if (isCurrent) link.setAttribute("aria-current", "location");
    else link.removeAttribute("aria-current");
  });
}

if (experienceJumpLinks.length && experienceSections.length) {
  let experienceFrame = 0;
  const syncExperienceJump = () => {
    experienceFrame = 0;
    const stickyOffset = window.matchMedia("(max-width: 720px)").matches ? 112 : 68;
    const marker = window.scrollY + stickyOffset;
    const currentSection = experienceSections.reduce((current, section) => {
      const sectionTop = section.getBoundingClientRect().top + window.scrollY;
      return sectionTop <= marker ? section : current;
    }, experienceSections[0]);
    setActiveExperienceJump(currentSection.id);
  };

  experienceJumpLinks.forEach((link) => link.addEventListener("click", () => {
    setActiveExperienceJump(link.getAttribute("href").slice(1));
  }));
  window.addEventListener("scroll", () => {
    if (!experienceFrame) experienceFrame = requestAnimationFrame(syncExperienceJump);
  }, { passive: true });
  window.addEventListener("resize", syncExperienceJump, { passive: true });
  syncExperienceJump();
}

const experienceTimeline = document.querySelector(".experience");
const timelineItems = experienceTimeline ? [
  ...experienceTimeline.querySelectorAll(".resume-group > .resume-row"),
  ...experienceTimeline.querySelectorAll(".resume-entry"),
  ...experienceTimeline.querySelectorAll(".honors-group p")
] : [];

if (experienceTimeline && timelineItems.length) {
  experienceTimeline.classList.add("timeline-enhanced");
  let timelineFrame = 0;
  const syncTimelineHighlight = () => {
    timelineFrame = 0;
    const focusLine = window.innerHeight * 0.42;
    let currentItem = timelineItems[0];
    let closestDistance = Number.POSITIVE_INFINITY;

    timelineItems.forEach((item) => {
      const rect = item.getBoundingClientRect();
      const distance = focusLine < rect.top
        ? rect.top - focusLine
        : focusLine > rect.bottom
          ? focusLine - rect.bottom
          : 0;
      if (distance < closestDistance) {
        closestDistance = distance;
        currentItem = item;
      }
    });
    timelineItems.forEach((item) => item.classList.toggle("is-current", item === currentItem));
  };

  window.addEventListener("scroll", () => {
    if (!timelineFrame) timelineFrame = requestAnimationFrame(syncTimelineHighlight);
  }, { passive: true });
  window.addEventListener("resize", syncTimelineHighlight, { passive: true });
  syncTimelineHighlight();
}
