function createProjectCodeArt(canvas) {
  const card = canvas.closest(".work-card");
  if (!card) return;
  const kind = canvas.dataset.codeArt;
  const sourcePath = kind === "hihi"
    ? "assets/hihi-placeholder.png"
    : "assets/work_cover_1.png";
  const image = new Image();
  const particles = [];
  let loaded = false;
  let visible = false;
  let gather = reduceMotionQuery.matches ? .9 : .28;
  let targetGather = gather;
  let previousFrame = 0;
  let phase = 0;
  let pointer = { x: -999, y: -999, active: false };
  let artBox = { x: 0, y: 0, width: 0, height: 0 };

  const rebuildParticles = () => {
    if (!loaded) return;
    const { width, height } = sizeCanvas(canvas);
    const mobile = width < 721;
    const sample = document.createElement("canvas");
    const sampleContext = sample.getContext("2d", { willReadFrequently: true });
    const sampleWidth = kind === "hihi" ? 250 : 180;
    const sampleHeight = Math.max(1, Math.round(sampleWidth * image.naturalHeight / image.naturalWidth));
    sample.width = sampleWidth;
    sample.height = sampleHeight;
    sampleContext.drawImage(image, 0, 0, sampleWidth, sampleHeight);
    const pixels = sampleContext.getImageData(0, 0, sampleWidth, sampleHeight).data;
    const candidates = [];
    const step = kind === "hihi" ? 3 : 2;
    for (let y = 0; y < sampleHeight; y += step) {
      for (let x = 0; x < sampleWidth; x += step) {
        const offset = (y * sampleWidth + x) * 4;
        const alpha = pixels[offset + 3];
        const luminance = pixels[offset] * .2126 + pixels[offset + 1] * .7152 + pixels[offset + 2] * .0722;
        const include = kind === "hihi" ? alpha > 60 : alpha > 80 && luminance < 164;
        if (include) candidates.push({ nx: x / sampleWidth, ny: y / sampleHeight });
      }
    }

    const maxParticles = mobile ? (kind === "hihi" ? 180 : 290) : (kind === "hihi" ? 320 : 520);
    particles.length = 0;
    if (!candidates.length) return;
    const stride = candidates.length / Math.min(maxParticles, candidates.length);
    for (let i = 0; i < Math.min(maxParticles, candidates.length); i += 1) {
      const candidate = candidates[Math.floor(i * stride + Math.random() * Math.max(1, stride - 1))];
      particles.push({
        ...candidate,
        sx: .04 + Math.random() * .92,
        sy: .08 + Math.random() * .84,
        glyph: codeGlyphs[(i * 7 + (kind === "hihi" ? 3 : 0)) % codeGlyphs.length],
        size: (mobile ? 6.8 : 8) + Math.random() * (mobile ? 2.8 : 3.8),
        offset: Math.random() * Math.PI * 2
      });
    }

    const imageRatio = image.naturalWidth / image.naturalHeight;
    const maxWidth = width * (mobile ? .9 : kind === "hihi" ? .72 : .6);
    const maxHeight = height * (mobile ? .72 : kind === "hihi" ? .7 : .78);
    const artWidth = Math.min(maxWidth, maxHeight * imageRatio);
    const artHeight = artWidth / imageRatio;
    artBox = {
      x: kind === "hihi" ? width * .14 : width * .34,
      y: kind === "hihi" ? height * .15 : height * .08,
      width: artWidth,
      height: artHeight
    };
    if (mobile) {
      artBox.x = (width - artWidth) / 2;
      artBox.y = height * (kind === "hihi" ? .27 : .17);
    }
  };

  const render = (time = 0) => {
    if (!loaded) return;
    const { context, width, height } = sizeCanvas(canvas);
    context.clearRect(0, 0, width, height);
    gather += (targetGather - gather) * (reduceMotionQuery.matches ? 1 : .085);
    phase += kind === "hihi" ? .035 : .022;
    const styles = getComputedStyle(card);
    const ink = styles.getPropertyValue("--card-ink").trim() || "#4b5375";
    const accent = styles.getPropertyValue("--card-accent").trim() || ink;
    const easedGather = gather * gather * (3 - 2 * gather);

    particles.forEach((particle, index) => {
      const targetX = artBox.x + particle.nx * artBox.width;
      const targetY = artBox.y + particle.ny * artBox.height;
      let x = particle.sx * width * (1 - easedGather) + targetX * easedGather;
      let y = particle.sy * height * (1 - easedGather) + targetY * easedGather;

      if (pointer.active && !reduceMotionQuery.matches) {
        const dx = x - pointer.x;
        const dy = y - pointer.y;
        const distance = Math.max(1, Math.hypot(dx, dy));
        const radius = kind === "hihi" ? 190 : 145;
        const influence = distance < radius ? (1 - distance / radius) : 0;
        if (kind === "hihi") {
          const jelly = Math.sin(phase * 2.2 + particle.offset) * influence * 12;
          x += dx / distance * influence * 16 + jelly;
          y += dy / distance * influence * 10 + Math.cos(phase + particle.offset) * influence * 7;
        } else {
          const ripple = Math.sin(distance * .09 - phase * 5) * influence * 9;
          x += dx / distance * ripple;
          y += dy / distance * ripple;
        }
      }

      const alpha = .13 + easedGather * (kind === "hihi" ? .27 : .235);
      context.fillStyle = index % 5 === 0 ? accent : ink;
      context.globalAlpha = alpha;
      context.font = `600 ${particle.size}px Roboto Mono, monospace`;
      context.fillText(particle.glyph, x, y);
    });
    context.globalAlpha = 1;
  };

  const animate = (time) => {
    const frameInterval = kind === "hihi" ? 50 : 34;
    if (visible && (time - previousFrame > frameInterval || reduceMotionQuery.matches)) {
      previousFrame = time;
      render(time);
    }
    if (!reduceMotionQuery.matches) requestAnimationFrame(animate);
  };

  const updatePointer = (event) => {
    const rect = canvas.getBoundingClientRect();
    pointer.x = event.clientX - rect.left;
    pointer.y = event.clientY - rect.top;
    pointer.active = true;
  };
  card.addEventListener("pointermove", updatePointer, { passive: true });
  card.addEventListener("pointerdown", updatePointer, { passive: true });
  card.addEventListener("pointerenter", () => { if (finePointerQuery.matches) targetGather = 1; });
  card.addEventListener("pointerleave", () => {
    pointer.active = false;
    if (finePointerQuery.matches) targetGather = .28;
  });
  card.addEventListener("focusin", () => { targetGather = 1; });
  card.addEventListener("focusout", () => { targetGather = finePointerQuery.matches ? .28 : targetGather; });

  const syncMobileGather = () => {
    if (finePointerQuery.matches || reduceMotionQuery.matches) return;
    const rect = card.getBoundingClientRect();
    const centerDistance = Math.abs(rect.top + rect.height / 2 - window.innerHeight / 2);
    targetGather = Math.max(.18, Math.min(.94, 1 - centerDistance / (window.innerHeight * .86)));
  };
  let scrollFrame = 0;
  window.addEventListener("scroll", () => {
    if (scrollFrame) return;
    scrollFrame = requestAnimationFrame(() => {
      scrollFrame = 0;
      syncMobileGather();
    });
  }, { passive: true });

  new ResizeObserver(() => {
    rebuildParticles();
    if (reduceMotionQuery.matches) render();
  }).observe(canvas);

  const loadArtwork = () => {
    if (image.src) return;
    image.addEventListener("load", () => {
      loaded = true;
      rebuildParticles();
      syncMobileGather();
      if (reduceMotionQuery.matches) render();
    }, { once: true });
    image.src = sourcePath;
  };

  if ("IntersectionObserver" in window) {
    new IntersectionObserver((entries) => {
      visible = entries[0]?.isIntersecting ?? false;
      if (visible) loadArtwork();
    }, { rootMargin: "320px 0px" }).observe(card);
  } else {
    visible = true;
    loadArtwork();
  }
  if (!reduceMotionQuery.matches) requestAnimationFrame(animate);
}

function createHeroTypewriter() {
  const paragraphs = [...document.querySelectorAll(".hero-copy-details > p")];
  if (!paragraphs.length || reduceMotionQuery.matches) return;
  const textJobs = paragraphs.map((paragraph) => {
    const label = paragraph.textContent.trim();
    paragraph.style.minHeight = `${Math.ceil(paragraph.getBoundingClientRect().height)}px`;
    paragraph.setAttribute("aria-label", label);
    const walker = document.createTreeWalker(paragraph, NodeFilter.SHOW_TEXT);
    const nodes = [];
    while (walker.nextNode()) {
      const node = walker.currentNode;
      nodes.push({ node, value: node.nodeValue });
      node.nodeValue = "";
    }
    return { paragraph, nodes };
  });

  let jobIndex = 0;
  let nodeIndex = 0;
  let characterIndex = 0;
  let cancelled = false;
  let timer = 0;
  const caret = document.createElement("span");
  caret.className = "typewriter-caret";
  caret.setAttribute("aria-hidden", "true");
  caret.textContent = "▋";

  const finish = () => {
    caret.remove();
    textJobs.forEach(({ paragraph }) => {
      paragraph.classList.remove("is-typing");
      paragraph.style.removeProperty("min-height");
      paragraph.removeAttribute("aria-label");
    });
  };

  const typeNext = () => {
    if (cancelled || jobIndex >= textJobs.length) {
      finish();
      return;
    }
    const job = textJobs[jobIndex];
    textJobs.forEach(({ paragraph }, index) => paragraph.classList.toggle("is-typing", index === jobIndex));
    const token = job.nodes[nodeIndex];
    if (!token) {
      jobIndex += 1;
      nodeIndex = 0;
      characterIndex = 0;
      timer = window.setTimeout(typeNext, 260);
      return;
    }
    if (characterIndex >= token.value.length) {
      nodeIndex += 1;
      characterIndex = 0;
      typeNext();
      return;
    }
    const character = token.value[characterIndex++];
    token.node.nodeValue += character;
    token.node.parentNode?.insertBefore(caret, token.node.nextSibling);
    const pause = /[.!?。！？]/.test(character) ? 105 : /[,，;；:：]/.test(character) ? 58 : character === " " ? 8 : 17;
    timer = window.setTimeout(typeNext, pause);
  };

  const cancelTyping = () => {
    if (cancelled) return;
    cancelled = true;
    window.clearTimeout(timer);
    finish();
  };
  languageToggles.forEach((toggle) => toggle.addEventListener("click", cancelTyping));
  timer = window.setTimeout(typeNext, 650);
}

function createExperienceParticleWaves() {
  const canvas = document.querySelector("[data-experience-particles]");
  const section = canvas?.closest(".experience");
  if (!canvas || !section) return;

  let particles = [];
  let visible = false;
  let previousFrame = 0;
  let scrollPhase = window.scrollY;
  let pointer = { x: -999, y: -999, strength: 0 };

  const seedParticles = () => {
    const { width, height } = sizeCanvas(canvas);
    const mobile = width < 721;
    const clusterCount = Math.ceil(height / (mobile ? 470 : 370)) + 1;
    const count = mobile
      ? Math.min(440, Math.max(310, Math.round(width * height / 5100)))
      : Math.min(980, Math.max(650, Math.round(width * height / 3700)));
    const clusterX = [.16, .48, .8, .31, .68, .2, .56, .84];
    particles = Array.from({ length: count }, (_, index) => {
      const depth = .32 + Math.random() * .68;
      const clustered = Math.random() < .79;
      const common = {
        phase: Math.random() * Math.PI * 2,
        depth,
        size: (mobile ? 6.2 : 6.8) + Math.random() * (mobile ? 3.2 : 4.4),
        glyph: index % 4 === 0 ? codeGlyphs[(index * 7) % codeGlyphs.length] : (index % 3 ? "·" : "•"),
        pale: index % 5 === 0
      };
      if (!clustered) {
        return {
          ...common,
          type: "ambient",
          x: 24 + Math.random() * Math.max(1, width - 48),
          y: 60 + Math.random() * Math.max(1, height - 120),
          drift: 4 + Math.random() * 12
        };
      }
      const cluster = index % clusterCount;
      return {
        ...common,
        type: "cluster",
        centerX: width * clusterX[cluster % clusterX.length] + (Math.random() - .5) * width * .08,
        centerY: (cluster + .48) * height / clusterCount + (Math.random() - .5) * (mobile ? 80 : 110),
        angle: Math.random() * Math.PI * 2,
        radius: 22 + Math.pow(Math.random(), .7) * (mobile ? 132 : 220),
        stretchX: .7 + Math.random() * .72,
        stretchY: .28 + Math.random() * .38,
        direction: index % 2 ? 1 : -1
      };
    });
  };

  const render = (time) => {
    const { context, width, height } = sizeCanvas(canvas);
    context.clearRect(0, 0, width, height);
    const sectionTop = section.getBoundingClientRect().top + window.scrollY;
    const parallax = (scrollPhase - sectionTop) * .018;
    pointer.strength *= .965;

    if (finePointerQuery.matches && pointer.strength > .025) {
      const ripplePhase = (time * .00062) % 1;
      for (let ring = 0; ring < 3; ring += 1) {
        const progress = (ripplePhase + ring / 3) % 1;
        const radius = 24 + progress * 132;
        const alpha = pointer.strength * (1 - progress) * .58;
        context.globalAlpha = alpha;
        context.fillStyle = "#4f80c9";
        context.font = "600 7px Roboto Mono, monospace";
        for (let glyphIndex = 0; glyphIndex < 18; glyphIndex += 1) {
          const angle = (Math.PI * 2 * glyphIndex) / 18 + progress * .7;
          context.fillText(
            codeGlyphs[(glyphIndex + ring * 3) % codeGlyphs.length],
            pointer.x + Math.cos(angle) * radius,
            pointer.y + Math.sin(angle) * radius * .42
          );
        }
      }
      context.globalAlpha = 1;
    }

    particles.forEach((particle) => {
      let x;
      let y;
      if (particle.type === "cluster") {
        const orbit = particle.angle + time * .000018 * particle.direction * particle.depth;
        x = particle.centerX + Math.cos(orbit) * particle.radius * particle.stretchX;
        y = particle.centerY + Math.sin(orbit) * particle.radius * particle.stretchY;
      } else {
        x = particle.x + Math.sin(time * .0002 + particle.phase) * particle.drift;
        y = particle.y + Math.cos(time * .00016 + particle.phase) * particle.drift * .6;
      }
      y += parallax * particle.depth;
      const dx = x - pointer.x;
      const dy = y - pointer.y;
      const distance = Math.max(1, Math.hypot(dx, dy));
      const reach = width < 721 ? 145 : 220;
      const influence = distance < reach ? (1 - distance / reach) * pointer.strength : 0;
      if (influence) {
        const ripple = Math.sin(distance * .09 - time * .007 + particle.phase) * influence * 30;
        const swirl = Math.cos(distance * .045 + time * .002) * influence * 9;
        x += dx / distance * ripple - dy / distance * swirl;
        y += dy / distance * ripple + dx / distance * swirl;
      }

      const edgeFade = Math.min(1, x / 70, (width - x) / 70, y / 90, (height - y) / 90);
      if (edgeFade <= 0) return;
      const alpha = (.14 + particle.depth * .14 + influence * .4) * edgeFade;
      context.globalAlpha = alpha;
      context.fillStyle = particle.pale ? "#a9c4ea" : "#4f80c9";
      context.font = `600 ${particle.size}px Roboto Mono, monospace`;
      context.fillText(particle.glyph, x, y);
    });
    context.globalAlpha = 1;
  };

  const animate = (time) => {
    if (visible && time - previousFrame > 40) {
      previousFrame = time;
      render(time);
    }
    if (!reduceMotionQuery.matches) requestAnimationFrame(animate);
  };

  const updatePointer = (event) => {
    if (!finePointerQuery.matches) return;
    const rect = canvas.getBoundingClientRect();
    pointer.x = event.clientX - rect.left;
    pointer.y = event.clientY - rect.top;
    pointer.strength = .72;
  };
  section.addEventListener("pointermove", updatePointer, { passive: true });
  section.addEventListener("pointerleave", () => { pointer.strength = 0; });
  window.addEventListener("scroll", () => { scrollPhase = window.scrollY; }, { passive: true });
  new ResizeObserver(() => {
    seedParticles();
    if (reduceMotionQuery.matches) render(0);
  }).observe(canvas);
  if ("IntersectionObserver" in window) {
    new IntersectionObserver((entries) => {
      visible = entries[0]?.isIntersecting ?? false;
      if (visible && reduceMotionQuery.matches) render(0);
    }, { rootMargin: "160px" }).observe(section);
  } else {
    visible = true;
  }
  seedParticles();
  if (reduceMotionQuery.matches) render(0);
  else requestAnimationFrame(animate);
}

function createExperienceShapeParticles() {
  const canvas = document.querySelector("[data-experience-shape-particles]");
  const section = canvas?.closest(".experience");
  if (!canvas || !section) return;

  let particles = [];
  let obstacleRects = [];
  let visible = false;
  let previousFrame = 0;
  let morphStartedAt = 0;
  let activeShape = section.dataset.activeSection || "education";
  let pointer = { x: -999, y: -999, strength: 0 };

  const shapes = new Set(["education", "internships", "projects", "entrepreneurship", "honors"]);
  const clamp = (value, min, max) => Math.max(min, Math.min(max, value));
  const hash = (value) => {
    const raw = Math.sin(value * 12.9898 + 78.233) * 43758.5453;
    return raw - Math.floor(raw);
  };
  const easeMorph = (value) => 1 - Math.pow(1 - clamp(value, 0, 1), 3);

  const pointForShape = (shape, index, count) => {
    const u = (index + .5) / count;
    const jitterX = (hash(index * 3.17 + 1) - .5);
    const jitterY = (hash(index * 5.83 + 2) - .5);

    if (shape === "internships") {
      if (index % 11 === 0) {
        return { x: -.24 + hash(index + 8) * .48, y: jitterY * .18 };
      }
      const side = index % 2 ? 1 : -1;
      const local = Math.floor(index / 2);
      const angle = Math.PI * 2 * hash(local * 1.73 + 5);
      const radius = Math.sqrt(hash(local * 2.31 + 9));
      return {
        x: side * .44 + Math.cos(angle) * radius * .46,
        y: Math.sin(angle) * radius * .68
      };
    }

    if (shape === "projects") {
      const columns = 16;
      const rows = Math.ceil(count / columns);
      const column = index % columns;
      const row = Math.floor(index / columns);
      const moduleOffsetX = column < columns / 2 ? -.055 : .055;
      const moduleOffsetY = row < rows / 2 ? -.05 : .05;
      return {
        x: (column / (columns - 1) - .5) * 1.62 + moduleOffsetX + jitterX * .035,
        y: (row / Math.max(1, rows - 1) - .5) * 1.25 + moduleOffsetY + jitterY * .035
      };
    }

    if (shape === "entrepreneurship") {
      const angle = .7 + u * Math.PI * 6.4;
      const radius = .08 + u * .9;
      return {
        x: Math.cos(angle) * radius + jitterX * .045,
        y: Math.sin(angle) * radius * .76 + jitterY * .045
      };
    }

    if (shape === "honors") {
      const angle = u * Math.PI * 4;
      const petal = .5 + .3 * Math.cos(angle * 5);
      const inner = index % 4 === 0 ? .58 : 1;
      return {
        x: Math.cos(angle) * petal * inner + jitterX * .035,
        y: Math.sin(angle) * petal * inner * .94 + jitterY * .035
      };
    }

    const ring = index % 3;
    const angle = Math.PI * 2 * hash(index * 1.91 + ring * 11);
    const radius = .32 + ring * .25 + jitterX * .045;
    return {
      x: Math.cos(angle) * radius,
      y: Math.sin(angle) * radius * (.58 + ring * .08)
    };
  };

  const resolvePoint = (particle, time) => {
    const progress = reduceMotionQuery.matches ? 1 : easeMorph((time - morphStartedAt) / 840);
    return {
      x: particle.fromX + (particle.toX - particle.fromX) * progress,
      y: particle.fromY + (particle.toY - particle.fromY) * progress
    };
  };

  const setShape = (shape, time = performance.now()) => {
    const nextShape = shapes.has(shape) ? shape : "education";
    if (nextShape === activeShape && particles.length) return;
    particles.forEach((particle, index) => {
      const current = resolvePoint(particle, time);
      const target = pointForShape(nextShape, index, particles.length);
      particle.fromX = current.x;
      particle.fromY = current.y;
      particle.toX = target.x;
      particle.toY = target.y;
    });
    activeShape = nextShape;
    morphStartedAt = time;
  };

  const refreshObstacleRects = () => {
    const sectionRect = section.getBoundingClientRect();
    obstacleRects = [...section.querySelectorAll(
      ".resume-group h3, .resume-row > time, .resume-row > strong, .resume-row > span, .resume-entry > p, .honors-group > p"
    )].flatMap((element) => {
      const range = document.createRange();
      range.selectNodeContents(element);
      return [...range.getClientRects()]
        .filter((rect) => rect.width > 1 && rect.height > 1)
        .map((rect) => ({
          left: rect.left - sectionRect.left - 12,
          right: rect.right - sectionRect.left + 12,
          top: rect.top - sectionRect.top - 8,
          bottom: rect.bottom - sectionRect.top + 8
        }));
    });
  };

  const isObstructed = (x, y, size) => obstacleRects.some((rect) => (
    x + size > rect.left && x - size < rect.right && y + size > rect.top && y - size < rect.bottom
  ));

  const roundedSquare = (context, x, y, size, radius) => {
    const half = size / 2;
    const left = x - half;
    const top = y - half;
    const right = x + half;
    const bottom = y + half;
    context.beginPath();
    context.moveTo(left + radius, top);
    context.lineTo(right - radius, top);
    context.quadraticCurveTo(right, top, right, top + radius);
    context.lineTo(right, bottom - radius);
    context.quadraticCurveTo(right, bottom, right - radius, bottom);
    context.lineTo(left + radius, bottom);
    context.quadraticCurveTo(left, bottom, left, bottom - radius);
    context.lineTo(left, top + radius);
    context.quadraticCurveTo(left, top, left + radius, top);
    context.closePath();
    context.fill();
  };

  const seedParticles = () => {
    const { width } = sizeCanvas(canvas, 1.35);
    if (width <= 720) {
      particles = [];
      return;
    }
    const count = width < 1050 ? 220 : 320;
    const initialShape = shapes.has(section.dataset.activeSection) ? section.dataset.activeSection : activeShape;
    particles = Array.from({ length: count }, (_, index) => {
      const point = pointForShape(initialShape, index, count);
      return {
        fromX: point.x,
        fromY: point.y,
        toX: point.x,
        toY: point.y,
        x: Number.NaN,
        y: Number.NaN,
        phase: hash(index * 4.7) * Math.PI * 2,
        size: 3.2 + hash(index * 7.1) * 5.8,
        square: index % 5 === 0 || index % 13 === 0,
        color: index % 7 === 0 ? "#4f80c9" : index % 3 === 0 ? "#78aee3" : "#9fc5ec",
        alpha: .7 + hash(index * 9.7) * .3
      };
    });
    activeShape = initialShape;
    morphStartedAt = performance.now();
    refreshObstacleRects();
  };

  const render = (time) => {
    const { context, width, height } = sizeCanvas(canvas, 1.35);
    context.clearRect(0, 0, width, height);
    if (width <= 720 || !particles.length) return;

    pointer.strength *= .92;
    const sectionRect = section.getBoundingClientRect();
    const centerX = width * (width < 1050 ? .83 : .845);
    const centerY = clamp(-sectionRect.top + window.innerHeight * .5, 190, height - 190);
    const sculptureScale = Math.min(272, width * .17, window.innerHeight * .34);
    const followStrength = reduceMotionQuery.matches ? 1 : .115;

    particles.forEach((particle, index) => {
      const point = resolvePoint(particle, time);
      const breathing = reduceMotionQuery.matches ? 0 : Math.sin(time * .00135 + particle.phase) * 2.6;
      const targetX = centerX + point.x * sculptureScale + Math.cos(particle.phase) * breathing;
      const targetY = centerY + point.y * sculptureScale + Math.sin(particle.phase) * breathing;
      particle.x = Number.isFinite(particle.x) ? particle.x + (targetX - particle.x) * followStrength : targetX;
      particle.y = Number.isFinite(particle.y) ? particle.y + (targetY - particle.y) * followStrength : targetY;
      let x = particle.x;
      let y = particle.y;

      const dx = x - pointer.x;
      const dy = y - pointer.y;
      const distance = Math.max(1, Math.hypot(dx, dy));
      const reach = 96;
      const influence = distance < reach ? (1 - distance / reach) * pointer.strength : 0;
      if (influence) {
        const push = influence * influence * 42;
        x += dx / distance * push;
        y += dy / distance * push;
      }

      if (isObstructed(x, y, particle.size + 2)) return;
      const edgeFade = Math.max(0, Math.min(1, x / 48, (width - x) / 48, y / 80, (height - y) / 80));
      if (!edgeFade) return;
      const core = index % 17 === 0 ? .08 : 0;
      context.globalAlpha = Math.min(.34, (.18 + core + influence * .13) * particle.alpha) * edgeFade;
      context.fillStyle = particle.color;
      if (particle.square) {
        roundedSquare(context, x, y, particle.size, Math.max(1.5, particle.size * .32));
      } else {
        context.beginPath();
        context.arc(x, y, particle.size * .46, 0, Math.PI * 2);
        context.fill();
      }
    });
    context.globalAlpha = 1;
  };

  const animate = (time) => {
    if (visible && time - previousFrame > 32) {
      previousFrame = time;
      render(time);
    }
    if (!reduceMotionQuery.matches) requestAnimationFrame(animate);
  };

  const updatePointer = (event) => {
    if (!finePointerQuery.matches) return;
    const rect = canvas.getBoundingClientRect();
    pointer.x = event.clientX - rect.left;
    pointer.y = event.clientY - rect.top;
    pointer.strength = 1;
  };

  section.addEventListener("experience-section-change", (event) => {
    setShape(event.detail?.sectionId || "education");
    refreshObstacleRects();
    if (reduceMotionQuery.matches) render(performance.now());
  });
  section.addEventListener("pointermove", updatePointer, { passive: true });
  section.addEventListener("pointerleave", () => { pointer.strength = 0; });
  new ResizeObserver(() => {
    seedParticles();
    if (reduceMotionQuery.matches) render(0);
  }).observe(canvas);
  window.addEventListener("load", refreshObstacleRects, { once: true });
  if (reduceMotionQuery.matches) {
    window.addEventListener("scroll", () => render(performance.now()), { passive: true });
  }
  if ("IntersectionObserver" in window) {
    new IntersectionObserver((entries) => {
      visible = entries[0]?.isIntersecting ?? false;
      if (visible && reduceMotionQuery.matches) render(0);
    }, { rootMargin: "180px" }).observe(section);
  } else {
    visible = true;
  }
  seedParticles();
  if (reduceMotionQuery.matches) render(performance.now());
  else requestAnimationFrame(animate);
}

