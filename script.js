function getProjectTitle(button) {
  return currentLanguage === "zh-CN"
    ? button?.dataset.projectTitleZh || button?.dataset.projectTitle
    : button?.dataset.projectTitle;
}

function applyLanguage(language) {
  currentLanguage = language === "zh-CN" ? "zh-CN" : "en";
  const isChinese = currentLanguage === "zh-CN";
  document.documentElement.lang = currentLanguage;

  i18nTextNodes.forEach((node) => {
    const key = node.dataset.i18n;
    node.textContent = isChinese && zhTranslations[key] ? zhTranslations[key] : originalText.get(node);
  });
  i18nHtmlNodes.forEach((node) => {
    const key = node.dataset.i18nHtml;
    node.innerHTML = isChinese && zhTranslations[key] ? zhTranslations[key] : originalHtml.get(node);
  });
  i18nAriaNodes.forEach((node) => {
    const key = node.dataset.i18nAriaLabel;
    node.setAttribute("aria-label", isChinese && zhTranslations[key] ? zhTranslations[key] : originalAria.get(node));
  });
  i18nTitleNodes.forEach((node) => {
    const key = node.dataset.i18nTitle;
    node.setAttribute("title", isChinese && zhTranslations[key] ? zhTranslations[key] : originalTitle.get(node));
  });

  document.title = isChinese ? zhTranslations["page.title"] : englishPageTitle;
  if (metaDescription) metaDescription.content = isChinese ? zhTranslations["page.description"] : englishPageDescription;
  languageToggles.forEach((toggle) => {
    toggle.textContent = isChinese ? "EN" : "中文";
    toggle.setAttribute("aria-label", isChinese ? "Switch to English" : "切换为中文");
    toggle.setAttribute("aria-pressed", String(isChinese));
  });
  refreshUrbanScreen();

  if (dialog?.open && activeProjectButton && dialogTitle) {
    dialogTitle.textContent = getProjectTitle(activeProjectButton);
  }
}

